import { describe, expect, it } from 'vitest';
import { isPublicAddress } from './address-policy';

describe('isPublicAddress', () => {
  it.each([
    '127.0.0.1', '127.255.0.9', '10.1.2.3', '172.16.0.1', '172.31.255.255', '192.168.1.106', '169.254.169.254',
    '100.64.0.1', '0.0.0.0', '192.0.2.10', '198.18.0.1', '224.0.0.1', '255.255.255.255',
    '::', '::1', '[::1]', 'fe80::1', 'fe80::1%eth0', 'fc00::1', 'fd12:3456::1', 'ff02::1', '2001:db8::1',
    '::ffff:127.0.0.1', '::ffff:7f00:1', '::ffff:192.168.1.41', '::127.0.0.1', '64:ff9b::a00:1', '2002:c0a8:101::1',
    'not-an-ip', '', '1.2.3', '999.1.1.1',
  ])('blocks %s', (ip) => {
    expect(isPublicAddress(ip)).toBe(false);
  });

  it.each(['80.242.34.10', '8.8.8.8', '172.32.0.1', '100.128.0.1', '2a00:1450:4001:82a::200e', '::ffff:8.8.8.8', '[2606:4700::1111]'])(
    'allows %s',
    (ip) => {
      expect(isPublicAddress(ip)).toBe(true);
    },
  );
});
